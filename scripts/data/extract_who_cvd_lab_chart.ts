/**
 * Generates src/domain/scoring/whoCvdLabTable.ts from the archived WHO PDF:
 *   HEARTS technical package — Risk-based CVD management (WHO 2020, ISBN 9789240001367),
 *   Annex 2, PDF page 44 (printed page 42): "WHO cardiovascular disease risk laboratory-based charts —
 *   South-East Asia" (the page lists Cambodia). Annex 1 (PDF page 25) gives printed page 42 for this chart.
 *
 * The cell values are real text in the PDF (the page is rotated 90°), so they are read by position —
 * no manual transcription. The script fails loudly unless exactly 1400 cells are found and every
 * number inside the chart area is used exactly once.
 *
 * Run: npm run data:who-lab-chart
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { getDocument } from "pdfjs-dist/legacy/build/pdf.mjs";

const PDF = path.resolve(__dirname, "../../docs/references/sources/WHO_HEARTS_risk-based-CVD-management_2020.pdf");
const SHA256 = "1f836448bc5f0455b717d9c1d6fc4cb057a286b8303fa940bf14c356785e2510";
const OUT = path.resolve(__dirname, "../../src/domain/scoring/whoCvdLabTable.ts");
const PAGE = 44;
const PRINTED_PAGE = 42;

// Unrotated PDF coordinates. x runs down the age blocks (70–74 first), y runs across the column blocks.
const AGES = ["70-74", "65-69", "60-64", "55-59", "50-54", "45-49", "40-44"]; // in x order
const SBPS = [">=180", "160-179", "140-159", "120-139", "<120"]; // in x order within an age block
const AGE_X0 = 160.0;
const AGE_STEP = 50.1;
const SBP_STEP = 8.63;
// Column blocks in y order: without diabetes (men non-smoker, men smoker, women non-smoker, women smoker), then with diabetes.
const BLOCKS = [
  { diabetes: false, sex: "male", smoker: false, y: 142.8 },
  { diabetes: false, sex: "male", smoker: true, y: 207.4 },
  { diabetes: false, sex: "female", smoker: false, y: 272.1 },
  { diabetes: false, sex: "female", smoker: true, y: 336.7 },
  { diabetes: true, sex: "male", smoker: false, y: 451.4 },
  { diabetes: true, sex: "male", smoker: true, y: 516.0 },
  { diabetes: true, sex: "female", smoker: false, y: 580.7 },
  { diabetes: true, sex: "female", smoker: true, y: 645.3 },
] as const;
const COL_STEP = 11.47; // total cholesterol columns: <4, 4-4.9, 5-5.9, 6-6.9, >=7 mmol/l

async function main() {
  if (!fs.existsSync(PDF)) throw new Error(`Archived source missing: ${PDF}`);
  const bytes = fs.readFileSync(PDF);
  const sha = crypto.createHash("sha256").update(bytes).digest("hex");
  if (sha !== SHA256) throw new Error(`PDF checksum changed (${sha}); re-check the page before regenerating.`);

  const doc = await getDocument({ data: new Uint8Array(bytes) }).promise;
  const page = await doc.getPage(PAGE);
  const all = (await page.getTextContent()).items
    .filter((i): i is typeof i & { str: string; transform: number[] } => "str" in i)
    .map((i) => ({ s: i.str.trim(), x: i.transform[4], y: i.transform[5] }));

  const text = all.map((i) => i.s).join(" ");
  for (const must of ["WHO cardiovascular disease risk laboratory-based charts", "South-East Asia", "Cambodia", "People with Diabetes", "People without Diabetes", "Total cholesterol (mmol/l)"])
    if (!text.includes(must)) throw new Error(`Page ${PAGE} is missing "${must}" — has the PDF changed?`);

  // Chart-cell numbers only: skips the legend (x≈123), the "180" of the "≥180" SBP labels, the "7" of "≥7" and the page number.
  const nums = all.filter((o) => /^\d+$/.test(o.s) && o.x > 155 && o.x < 500 && o.y > 135 && o.y < 700 && !(o.s === "180" && (o.y > 395 && o.y < 405 || o.y > 705)));
  const used = new Set<object>();
  // table[diabetes][sex][smoker][age][sbp] = [5 cholesterol columns]
  const table: Record<string, Record<string, Record<string, Record<string, Record<string, number[]>>>>> = {};
  for (const [ai, age] of AGES.entries())
    for (const [si, sbp] of SBPS.entries()) {
      const x = AGE_X0 + ai * AGE_STEP + si * SBP_STEP;
      for (const b of BLOCKS) {
        const row: number[] = [];
        for (let c = 0; c < 5; c++) {
          const y = b.y + c * COL_STEP;
          const hits = nums.filter((o) => Math.abs(o.x - x) < 2.5 && Math.abs(o.y - y) < 3);
          if (hits.length !== 1) throw new Error(`Cell ${b.diabetes}/${b.sex}/${b.smoker}/${age}/${sbp}/${c}: ${hits.length} matches`);
          if (used.has(hits[0])) throw new Error(`Cell ${b.diabetes}/${b.sex}/${b.smoker}/${age}/${sbp}/${c} reuses a number`);
          used.add(hits[0]);
          row.push(Number(hits[0].s));
        }
        const dm = b.diabetes ? "diabetes" : "noDiabetes";
        const smk = b.smoker ? "smoker" : "nonSmoker";
        (((((table[dm] ??= {})[b.sex] ??= {})[smk] ??= {})[age] ??= {})[sbp] = row);
      }
    }
  if (used.size !== 1400 || nums.length !== 1400) throw new Error(`Expected 1400 cells, got ${used.size}/${nums.length}`);

  const ts = `// AUTO-GENERATED by scripts/data/extract_who_cvd_lab_chart.ts — do not edit by hand.
//
// Source: WHO. HEARTS technical package for cardiovascular disease management in primary health care:
// risk-based CVD management. Geneva: World Health Organization; 2020. ISBN 9789240001367.
// Annex 2, PDF page ${PAGE} (printed page ${PRINTED_PAGE}): "WHO cardiovascular disease risk laboratory-based charts —
// South-East Asia" (countries: Cambodia, Indonesia, Lao People's Democratic Republic, Malaysia, Maldives,
// Mauritius, Myanmar, Philippines, Seychelles, Sri Lanka, Thailand, Timor-Leste, Viet Nam). Licence: CC BY-NC-SA 3.0 IGO.
// Archived copy: docs/references/sources/WHO_HEARTS_risk-based-CVD-management_2020.pdf (sha256 ${SHA256}).
//
// Values are 10-year risk (%) of a fatal or non-fatal cardiovascular event, read from the PDF text layer.
// Extraction checks: exactly 1400 cells; monotonic in age, SBP, cholesterol, smoking and diabetes (see whoCvdLab.test.ts).
// VERIFIED_BY: TODO(VERIFY) — sample cells listed in docs/references/methods/who-cvd-lab/METHOD_CARD.md for a human check against page ${PAGE}.

export const WHO_CVD_LAB_SOURCE = {
  title: "WHO CVD risk laboratory-based chart — South-East Asia (HEARTS, 2020)",
  isbn: "9789240001367",
  page: ${PAGE},
  printedPage: ${PRINTED_PAGE},
  url: "https://www.who.int/publications/i/item/9789240001367",
} as const;

export const CHOL_GROUPS = ["<4", "4-4.9", "5-5.9", "6-6.9", ">=7"] as const;
export type CholGroup = (typeof CHOL_GROUPS)[number];

type AgeGroup = ${AGES.map((a) => JSON.stringify(a)).reverse().join(" | ")};
type SbpGroup = ${SBPS.map((a) => JSON.stringify(a)).reverse().join(" | ")};
type Row = readonly [number, number, number, number, number];

/** WHO_CVD_LAB_TABLE[diabetes][sex][smoker][ageGroup][sbpGroup][cholesterolColumn] = 10-year risk % */
export const WHO_CVD_LAB_TABLE: Record<
  "diabetes" | "noDiabetes",
  Record<"male" | "female", Record<"smoker" | "nonSmoker", Record<AgeGroup, Record<SbpGroup, Row>>>>
> = ${JSON.stringify(table, null, 2)};
`;
  fs.writeFileSync(OUT, ts);
  console.log(`Wrote ${OUT} (1400 cells from page ${PAGE}).`);
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
