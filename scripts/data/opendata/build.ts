/**
 * Open-data pipeline (Phase 2). Reads only data/raw (+ data/clean/facilities.geojson from the facility
 * pipeline) and writes everything to data/clean:
 *   areas_province.json · areas_district.json · areas_commune.json
 *   boundaries_province.geojson · boundaries_district.geojson · boundaries_commune.geojson (simplified)
 *   national_context.json · food_prices_province.json · data_quality_report.md
 * and data/manifest.json (provenance + SHA-256 of every raw input).
 *
 * Deterministic: no timestamps, sorted keys and rows, fixed rounding → identical bytes on every run.
 * Run: npm run data:build   (or: npx tsx scripts/data/opendata/build.ts)
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fromFile } from "geotiff";
import { DATASETS, DHS_INDICATOR_IDS } from "./sources";
import {
  addCell, cellIndex, emptyAcc, haversineKm, makeProvinceMatcher, median, mergeAcc, parseCsv, pearson,
  pointInRings, rasterize, ringsOf, round, stableStringify, summarise, bboxOf,
  type Acc, type Geometry, type Grid, type Ring,
} from "./lib";

const ROOT = path.resolve(__dirname, "../../..");
const RAW = path.join(ROOT, "data/raw");
const CLEAN = path.join(ROOT, "data/clean");
const read = (p: string) => fs.readFileSync(path.join(RAW, p), "utf8");
const readJson = (p: string) => JSON.parse(read(p));
const write = (file: string, text: string) => fs.writeFileSync(path.join(CLEAN, file), text);

const report: string[] = [];
const issues: string[] = [];
const say = (s = "") => { report.push(s); console.log(s); };

// ---------------------------------------------------------------- boundaries
interface Area { pcode: string; name: string; parent?: string; province?: string; rings: Ring[]; bbox: number[]; center?: [number, number] }
type Feature = { properties: Record<string, string | number | null>; geometry: Geometry };

function loadAreas(file: string, level: 1 | 2 | 3): Area[] {
  const g = readJson(`admin/${file}`) as { features: Feature[] };
  return g.features.map((f) => {
    const p = f.properties;
    const rings = ringsOf(f.geometry);
    return {
      pcode: String(p[`adm${level}_pcode`]),
      name: String(p[`adm${level}_name`]),
      parent: level > 1 ? String(p[`adm${level - 1}_pcode`]) : undefined,
      province: level > 1 ? String(p.adm1_pcode) : undefined,
      rings,
      bbox: bboxOf(rings),
      center: p.center_lat != null && p.center_lon != null ? ([Number(p.center_lat), Number(p.center_lon)] as [number, number]) : undefined,
    };
  }).sort((a, b) => a.pcode.localeCompare(b.pcode));
}

async function readTif(p: string) {
  const img = await (await fromFile(path.join(RAW, p))).getImage();
  const [ox, oy] = img.getOrigin();
  const [rx] = img.getResolution();
  const grid: Grid = { ox, oy, res: Math.abs(rx), width: img.getWidth(), height: img.getHeight() };
  const [data] = (await img.readRasters()) as unknown as [Float32Array];
  return { grid, data, nodata: img.getGDALNoData() };
}

const sha256 = (file: string) => crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");

async function main() {
  say("# Open data quality report");
  say();
  say("Generated by `npm run data:build` (`scripts/data/opendata/build.ts`) from the raw files listed in `data/manifest.json`. Deterministic: the same raw files always give byte-identical outputs.");
  say();

  const provinces = loadAreas("khm_admin1.geojson", 1);
  const districts = loadAreas("khm_admin2.geojson", 2);
  const communes = loadAreas("khm_admin3.geojson", 3);
  say("## 1. Geography (COD-AB)");
  say();
  say(`- Provinces: **${provinces.length}** (expected 25) · districts: **${districts.length}** (expected 197) · communes: **${communes.length}** (expected 1,633)`);
  if (provinces.length !== 25 || districts.length !== 197) issues.push("Province/district count differs from 25/197");
  const orphanD = districts.filter((d) => !provinces.some((p) => p.pcode === d.parent));
  const orphanC = communes.filter((c) => !districts.some((d) => d.pcode === c.parent));
  say(`- Districts whose province P-code is missing: ${orphanD.length} · communes whose district P-code is missing: ${orphanC.length}`);
  say(`- Communes without a centre point in COD-AB: ${communes.filter((c) => !c.center).length} (polygon bounding-box centre used instead)`);
  say();

  // ---------------------------------------------------------------- population × travel time
  console.log("reading rasters…");
  const pop = await readTif("opendata/worldpop/khm_pop_2025_CN_100m_R2025A_v1.tif");
  const motor = await readTif("opendata/map/motorized_travel_time_to_healthcare_2019.tif");
  const walk = await readTif("opendata/map/walking_travel_time_to_healthcare_2019.tif");
  if (motor.grid.width !== walk.grid.width || motor.grid.ox !== walk.grid.ox) throw new Error("MAP layers are not aligned");

  // Rasterise communes onto the 100 m population grid (cell centre inside polygon → commune index + 1).
  console.log("rasterising communes…");
  const owner = new Uint16Array(pop.grid.width * pop.grid.height);
  let overlaps = 0;
  const cellsPerCommune = communes.map((c, i) =>
    rasterize(c.rings, pop.grid, (r, col) => {
      const k = r * pop.grid.width + col;
      if (owner[k]) overlaps++;
      else owner[k] = i + 1;
    }),
  );

  console.log("zonal statistics…");
  const acc: Acc[] = communes.map(emptyAcc);
  let popTotal = 0, popOutside = 0, popNoMotor = 0, popNoWalk = 0, popCells = 0;
  const travelAt = (t: typeof motor, lng: number, lat: number) => {
    const k = cellIndex(t.grid, lng, lat);
    if (k < 0) return null;
    const v = t.data[k];
    return v === t.nodata || v < 0 || !Number.isFinite(v) ? null : v;
  };
  const { grid } = pop;
  for (let r = 0; r < grid.height; r++) {
    const lat = grid.oy - (r + 0.5) * grid.res;
    for (let c = 0; c < grid.width; c++) {
      const k = r * grid.width + c;
      const p = pop.data[k];
      if (!(p > 0) || p === pop.nodata) continue;
      popTotal += p;
      popCells++;
      const o = owner[k];
      if (!o) { popOutside += p; continue; }
      const lng = grid.ox + (c + 0.5) * grid.res;
      const m = travelAt(motor, lng, lat);
      const w = travelAt(walk, lng, lat);
      if (m === null) popNoMotor += p;
      if (w === null) popNoWalk += p;
      addCell(acc[o - 1], p, m, w);
    }
  }
  const sumBy = (keyOf: (c: Area) => string) => {
    const m = new Map<string, Acc>();
    communes.forEach((c, i) => {
      const k = keyOf(c);
      if (!m.has(k)) m.set(k, emptyAcc());
      mergeAcc(m.get(k)!, acc[i]);
    });
    return m;
  };
  const accDistrict = sumBy((c) => c.parent!);
  const accProvince = sumBy((c) => c.province!);

  // COD-PS official totals
  const ps = parseCsv(read("opendata/cod-ps/khm_admpop_adm1_2024.csv"));
  const psH = ps[0];
  const col = (n: string) => psH.indexOf(n);
  const ps0 = parseCsv(read("opendata/cod-ps/khm_admpop_adm0_2024.csv"));
  const nationalOfficial = Number(ps0[1][ps0[0].indexOf("T_TL")]);
  const ageCols = psH.filter((h) => /^T_\d\d_\d\d$|^T_80Plus$/.test(h));
  const ageFrom = (h: string) => Number(h.slice(2, 4));
  const codps = new Map<string, { total: number; share20plus: number; share40to74: number }>();
  const unmatchedPs: string[] = [];
  for (const row of ps.slice(1)) {
    const pc = row[col("ADM1_PCODE")];
    if (!provinces.some((p) => p.pcode === pc)) { unmatchedPs.push(`${row[col("ADM1_EN")]} (${pc})`); continue; }
    const total = Number(row[col("T_TL")]);
    const sum = (f: (a: number) => boolean) => ageCols.filter((h) => f(ageFrom(h))).reduce((s, h) => s + Number(row[col(h)]), 0);
    codps.set(pc, { total, share20plus: sum((a) => a >= 20) / total, share40to74: sum((a) => a >= 40 && a < 75) / total });
  }

  say("## 2. Population (WorldPop 2025, 100 m) vs official totals (COD-PS 2024)");
  say();
  const inCommunes = popTotal - popOutside;
  const diffPct = (100 * (popTotal - nationalOfficial)) / nationalOfficial;
  say(`- WorldPop national sum: **${Math.round(popTotal).toLocaleString("en")}** · COD-PS 2024 national total: **${nationalOfficial.toLocaleString("en")}** · difference **${diffPct >= 0 ? "+" : ""}${diffPct.toFixed(1)}%** (target ±10%: ${Math.abs(diffPct) <= 10 ? "✅" : "❌"})`);
  if (Math.abs(diffPct) > 10) issues.push(`WorldPop total differs from COD-PS by ${diffPct.toFixed(1)}%`);
  say(`- Populated 100 m cells: ${popCells.toLocaleString("en")} · population in cells whose centre is outside every commune polygon: ${Math.round(popOutside).toLocaleString("en")} (${((100 * popOutside) / popTotal).toFixed(2)}%), not assigned to any area`);
  say(`- Grid cells claimed by two communes (overlapping polygons): ${overlaps} (first commune kept)`);
  const emptyCommunes = communes.filter((_, i) => acc[i].pop === 0);
  say(`- Communes with **no populated cell**: ${emptyCommunes.length}${emptyCommunes.length ? ` (${emptyCommunes.slice(0, 15).map((c) => `${c.name} ${c.pcode}, ${cellsPerCommune[communes.indexOf(c)]} cells`).join("; ")}${emptyCommunes.length > 15 ? "; …" : ""})` : ""}. Their population is reported as 0 and travel times as null.`);
  say(`- Population without a MAP travel time (cell is water/no-data in the MAP layer): motorised ${Math.round(popNoMotor).toLocaleString("en")} (${((100 * popNoMotor) / inCommunes).toFixed(2)}%), walking ${Math.round(popNoWalk).toLocaleString("en")} (${((100 * popNoWalk) / inCommunes).toFixed(2)}%). These people are excluded from travel-time averages only.`);
  say();
  say("| Province | WorldPop 2025 | COD-PS 2024 | Difference |");
  say("|---|---:|---:|---:|");
  for (const p of provinces) {
    const wp = accProvince.get(p.pcode)?.pop ?? 0;
    const off = codps.get(p.pcode)?.total;
    const d = off ? (100 * (wp - off)) / off : null;
    say(`| ${p.name} | ${Math.round(wp).toLocaleString("en")} | ${off?.toLocaleString("en") ?? "—"} | ${d === null ? "—" : `${d >= 0 ? "+" : ""}${d.toFixed(1)}%`} |`);
  }
  const bigDiff = provinces.filter((p) => {
    const off = codps.get(p.pcode)?.total;
    return off && Math.abs((accProvince.get(p.pcode)?.pop ?? 0) - off) / off > 0.1;
  });
  if (bigDiff.length) {
    say(`\n⚠️ Provinces where WorldPop and COD-PS differ by more than 10%: ${bigDiff.map((p) => p.name).join(", ")}. The two are independent estimates (WorldPop: satellite-based model; COD-PS: census-based projection). This pipeline uses WorldPop for district and commune population and keeps the official total alongside it for provinces.`);
    issues.push(`WorldPop vs COD-PS differ by more than 10% in: ${bigDiff.map((p) => p.name).join(", ")} (flagged, not adjusted)`);
  }
  if (unmatchedPs.length) say(`\nCOD-PS rows not matched to a COD-AB province: ${unmatchedPs.join(", ")}`);
  else say("\nAll 25 COD-PS rows matched COD-AB P-codes directly.");
  say();

  // ---------------------------------------------------------------- facilities
  type Fac = { id: string; name: string; type: string; lat: number; lng: number; source: string };
  const facs: Fac[] = JSON.parse(fs.readFileSync(path.join(CLEAN, "facilities.geojson"), "utf8")).features.map(
    (f: { properties: Fac }) => f.properties,
  );
  const TYPES = ["hospital", "health_centre", "health_post", "clinic", "other"] as const;
  type Counts = Record<(typeof TYPES)[number] | "total", number>;
  const zero = (): Counts => ({ hospital: 0, health_centre: 0, health_post: 0, clinic: 0, other: 0, total: 0 });
  const facCommune = new Map<string, Counts>();
  const unassignedFac: Fac[] = [];
  for (const f of facs) {
    const c = communes.find((a) => f.lng >= a.bbox[0] && f.lng <= a.bbox[2] && f.lat >= a.bbox[1] && f.lat <= a.bbox[3] && pointInRings(f.lng, f.lat, a.rings));
    if (!c) { unassignedFac.push(f); continue; }
    const k = c.pcode;
    if (!facCommune.has(k)) facCommune.set(k, zero());
    const t = (TYPES as readonly string[]).includes(f.type) ? (f.type as (typeof TYPES)[number]) : "other";
    facCommune.get(k)![t]++;
    facCommune.get(k)!.total++;
  }
  const rollup = (keyOf: (c: Area) => string) => {
    const m = new Map<string, Counts>();
    for (const c of communes) {
      const k = keyOf(c);
      if (!m.has(k)) m.set(k, zero());
      const src = facCommune.get(c.pcode);
      if (src) for (const t of [...TYPES, "total"] as const) m.get(k)![t] += src[t];
    }
    return m;
  };
  const facDistrict = rollup((c) => c.parent!);
  const facProvince = rollup((c) => c.province!);
  say("## 3. Facilities (data/clean/facilities.geojson: MoH 2010 + OSM 2026)");
  say();
  say(`- Facilities: ${facs.length} · assigned to a commune: ${facs.length - unassignedFac.length} · **not inside any commune polygon: ${unassignedFac.length}**${unassignedFac.length ? ` (${unassignedFac.map((f) => `${f.name} [${f.type}] ${f.lat.toFixed(4)},${f.lng.toFixed(4)}`).join("; ")})` : ""}`);
  const byType = Object.fromEntries(TYPES.map((t) => [t, facs.filter((f) => f.type === t).length]));
  say(`- By type: ${Object.entries(byType).map(([k, v]) => `${k} ${v}`).join(" · ")}`);
  say(`- "Hospital" includes MoH referral hospitals and OSM places tagged as hospitals (some private).`);
  say();

  // nearest hospital / health centre from each commune centre (straight line)
  const hospitals = facs.filter((f) => f.type === "hospital");
  const centres = facs.filter((f) => f.type === "health_centre");
  const nearest = (lat: number, lng: number, list: Fac[]) => {
    let best: Fac | null = null, d = Infinity;
    for (const f of list) {
      const x = haversineKm(lat, lng, f.lat, f.lng);
      if (x < d) { d = x; best = f; }
    }
    return { km: round(d, 1), name: best?.name ?? null, id: best?.id ?? null };
  };

  // ---------------------------------------------------------------- DHS (province)
  const dhs = readJson("opendata/dhs/kh2021dhs_subnational.json").Data as Record<string, string | number>[];
  const dhsNat = readJson("opendata/dhs/kh2021dhs_national.json").Data as Record<string, string | number>[];
  const matchProvince = makeProvinceMatcher(provinces.map((p) => ({ pcode: p.pcode, name: p.name })));
  const dhsByProv = new Map<string, Record<string, { value: number; n: number }>>();
  const dhsLabels = new Map<string, string | null>();
  const dhsIndicatorNames: Record<string, string> = {};
  for (const x of dhs) {
    const label = String(x.CharacteristicLabel);
    const pc = matchProvince(label);
    dhsLabels.set(label, pc);
    dhsIndicatorNames[String(x.IndicatorId)] = String(x.Indicator);
    if (!pc) continue;
    if (!dhsByProv.has(pc)) dhsByProv.set(pc, {});
    dhsByProv.get(pc)![String(x.IndicatorId)] = { value: Number(x.Value), n: Number(x.DenominatorUnweighted) };
  }
  say("## 4. DHS 2021–22 (province level, aggregated indicators from the DHS Program API)");
  say();
  say("Name matching (DHS label → COD-AB P-code). DHS publishes 14 survey regions plus the 25 provinces inside them; only province rows are used.");
  say();
  say("| DHS label | Matched P-code |");
  say("|---|---|");
  for (const [label, pc] of [...dhsLabels].sort((a, b) => a[0].localeCompare(b[0]))) say(`| ${label} | ${pc ?? "— (combined survey region, not used)"} |`);
  const dhsMissing = provinces.filter((p) => DHS_INDICATOR_IDS.some((id) => dhsByProv.get(p.pcode)?.[id] === undefined));
  say();
  say(`- Provinces with every DHS indicator: ${25 - dhsMissing.length}/25${dhsMissing.length ? ` (missing: ${dhsMissing.map((p) => p.name).join(", ")})` : ""}`);
  if (dhsMissing.length) issues.push("DHS indicators missing for some provinces");
  const smallN = [...dhsByProv].flatMap(([pc, v]) => Object.entries(v).filter(([, x]) => x.n < 250).map(([id, x]) => `${provinces.find((p) => p.pcode === pc)!.name} ${id} n=${x.n}`));
  say(`- Province estimates based on fewer than 250 respondents (less precise): ${smallN.length ? smallN.join("; ") : "none"}`);
  say("- All DHS figures describe people aged 15–49 (women's BMI: non-pregnant women 15–49). Confidence intervals are not published in the API response.");
  say();

  // ---------------------------------------------------------------- HeiGIT cross-check (province)
  const hg = parseCsv(read("opendata/heigit/KHM_primary_healthcare_access_wide.csv"));
  const hgH = hg[0];
  const hgI = (n: string) => hgH.indexOf(n);
  const hgProv = new Map<string, { s30: number; s60: number }>();
  const hgUnmatched = new Set<string>();
  for (const x of hg.slice(1)) {
    if (x[hgI("admin_level")] !== "ADM1") continue;
    const pc = matchProvince(x[hgI("name")]);
    if (!pc) { hgUnmatched.add(x[hgI("name")]); continue; }
    const range = Number(x[hgI("range")]);
    const share = Number(x[hgI("population_share")]);
    // HeiGIT omits time bands that contain nobody, so a province listed without a 30/60-min row has 0% there.
    const e = hgProv.get(pc) ?? { s30: 0, s60: 0 };
    if (range === 1800) e.s30 = share;
    if (range === 3600) e.s60 = share;
    hgProv.set(pc, e);
  }

  // ---------------------------------------------------------------- build area records
  const meta = {
    population: { source: "worldpop", year: "2025", note: "WorldPop constrained 100 m, summed over cells whose centre is inside the area" },
    population_official: { source: "cod-ps", year: "2024", note: "Province only" },
    adults_20plus_est: { source: "worldpop + cod-ps", year: "2025 / 2024", note: "WorldPop population × the province's share aged 20+ in COD-PS 2024" },
    travel: { source: "map-travel-time", year: "2019", note: "Population-weighted mean minutes to the nearest health facility (MAP's 2019 facility list); people where MAP has no value are excluded" },
    facilities: { source: "moh-facilities + osm-facilities", year: "2010 + 2026", note: "Counts by type inside the area; per 10,000 uses WorldPop 2025" },
    nearest: { source: "moh-facilities + osm-facilities + cod-ab", year: "2010 + 2026", note: "Straight-line km from the COD-AB commune centre point" },
    dhs: { source: "dhs-2021", year: "2021–22", note: "Province estimates, ages 15–49. Districts and communes inherit their province's value." },
  };
  const DHS_KEYS: Record<string, string> = {
    AN_NUTS_W_OWT: "women_overweight_or_obese_pct",
    AH_TOBC_M_ANY: "men_smoke_tobacco_pct",
    AH_TOBC_W_ANY: "women_smoke_tobacco_pct",
    AH_HINS_W_NON: "women_no_health_insurance_pct",
    AH_HINS_M_NON: "men_no_health_insurance_pct",
    RH_PAHC_W_DIS: "women_distance_is_problem_pct",
    HC_WIXQ_P_LOW: "population_lowest_wealth_quintile_pct",
  };
  const dhsRecord = (pc: string) =>
    Object.fromEntries(Object.entries(DHS_KEYS).map(([id, key]) => [key, round(dhsByProv.get(pc)?.[id]?.value, 1)]));

  const record = (a: Area, level: "province" | "district" | "commune", ac: Acc, fc: Counts) => {
    const s = summarise(ac);
    const prov = level === "province" ? a.pcode : a.province!;
    const share20 = codps.get(prov)?.share20plus ?? null;
    const base = {
      pcode: a.pcode,
      name_en: a.name,
      level,
      ...(level !== "province" ? { province_pcode: a.province } : {}),
      ...(level === "commune" ? { district_pcode: a.parent } : {}),
      population: s.population,
      adults_20plus_est: share20 === null ? null : Math.round(s.population * share20),
      travel_motor_mean_min: s.travel_motor_mean_min,
      travel_walk_mean_min: s.travel_walk_mean_min,
      pct_walk_over_60_min: s.pct_walk_over_60_min,
      pct_motor_over_30_min: s.pct_motor_over_30_min,
      facilities: fc,
      facilities_per_10k: s.population > 0 ? round((fc.total / s.population) * 1e4, 2) : null,
    };
    if (level === "province") {
      const off = codps.get(a.pcode);
      return {
        ...base,
        population_official_2024: off?.total ?? null,
        share_20plus_official: round(off?.share20plus, 4),
        share_40to74_official: round(off?.share40to74, 4),
        dhs: dhsRecord(a.pcode),
      };
    }
    if (level === "district") return { ...base, dhs: dhsRecord(prov) };
    const [clat, clng] = a.center ?? [(a.bbox[1] + a.bbox[3]) / 2, (a.bbox[0] + a.bbox[2]) / 2];
    return { ...base, nearest_hospital: nearest(clat, clng, hospitals), nearest_health_centre: nearest(clat, clng, centres) };
  };

  const provRecs = provinces.map((p) => record(p, "province", accProvince.get(p.pcode) ?? emptyAcc(), facProvince.get(p.pcode) ?? zero()));
  const distRecs = districts.map((d) => record(d, "district", accDistrict.get(d.pcode) ?? emptyAcc(), facDistrict.get(d.pcode) ?? zero()));
  const commRecs = communes.map((c, i) => record(c, "commune", acc[i], facCommune.get(c.pcode) ?? zero()));

  const header = (level: string) => ({
    level,
    licence_of_this_file: "CC BY 4.0 (SokhaPheap processed open data); see sources for each input's licence",
    citation: "SokhaPheap open data (2026), derived from COD-AB, WorldPop, Malaria Atlas Project, MoH, OpenStreetMap and DHS — see data/manifest.json",
    indicators: meta,
    dhs_indicators: Object.fromEntries(Object.entries(DHS_KEYS).map(([id, key]) => [key, { dhs_id: id, label: dhsIndicatorNames[id] }])),
  });
  write("areas_province.json", stableStringify({ ...header("province"), areas: provRecs }, 1));
  write("areas_district.json", stableStringify({ ...header("district"), areas: distRecs }, 1));
  write("areas_commune.json", stableStringify({ ...header("commune"), areas: commRecs }));

  // ---------------------------------------------------------------- range checks + spot checks
  say("## 5. Range checks");
  say();
  const all = [...provRecs, ...distRecs, ...commRecs] as Record<string, unknown>[];
  const bad: string[] = [];
  for (const a of all) {
    for (const [k, v] of Object.entries(a)) {
      if (typeof v !== "number") continue;
      if (/pct/.test(k) && (v < 0 || v > 100)) bad.push(`${a.pcode} ${k}=${v}`);
      if (/min$|population|per_10k|adults/.test(k) && v < 0) bad.push(`${a.pcode} ${k}=${v}`);
    }
    const d = a.dhs as Record<string, number | null> | undefined;
    if (d) for (const [k, v] of Object.entries(d)) if (v !== null && (v < 0 || v > 100)) bad.push(`${a.pcode} dhs.${k}=${v}`);
  }
  say(`- Values outside their possible range (percentages 0–100, minutes/population/counts ≥ 0): **${bad.length}**${bad.length ? ` → ${bad.slice(0, 10).join("; ")}` : " ✅"}`);
  if (bad.length) issues.push(`${bad.length} out-of-range values`);
  const nullTravel = { district: distRecs.filter((d) => d.travel_motor_mean_min === null).length, commune: commRecs.filter((c) => c.travel_motor_mean_min === null).length };
  say(`- Areas without a travel-time value: districts ${nullTravel.district}, communes ${nullTravel.commune}`);
  say(`- Commune coverage: ${commRecs.filter((c) => c.population > 0).length}/${communes.length} communes have population and travel values`);
  const outlierTravel = distRecs.filter((d) => (d.travel_motor_mean_min ?? 0) > 120).map((d) => `${d.name_en} ${d.travel_motor_mean_min} min`);
  say(`- Districts with mean motorised travel time > 120 min (outlier check): ${outlierTravel.length ? outlierTravel.join("; ") : "none"}`);
  say();

  say("## 6. Spot check: provinces by population-weighted motorised travel time (MAP 2019)");
  say();
  const sorted = [...provRecs].sort((a, b) => (a.travel_motor_mean_min ?? 0) - (b.travel_motor_mean_min ?? 0));
  const row = (p: (typeof provRecs)[number]) =>
    `| ${p.name_en} | ${p.travel_motor_mean_min} | ${p.travel_walk_mean_min} | ${p.pct_walk_over_60_min}% | ${p.facilities.total} | ${p.facilities_per_10k} |`;
  say("**Shortest (top 5)**");
  say();
  say("| Province | Motor mean (min) | Walk mean (min) | > 60 min walk | Facilities | per 10k |");
  say("|---|---:|---:|---:|---:|---:|");
  sorted.slice(0, 5).forEach((p) => say(row(p)));
  say();
  say("**Longest (bottom 5)**");
  say();
  say("| Province | Motor mean (min) | Walk mean (min) | > 60 min walk | Facilities | per 10k |");
  say("|---|---:|---:|---:|---:|---:|");
  sorted.slice(-5).reverse().forEach((p) => say(row(p)));
  say();
  const pp = provRecs.find((p) => p.pcode === "KH12")!;
  const maxFac = [...provRecs].sort((a, b) => b.facilities.total - a.facilities.total)[0];
  say(`- Phnom Penh shortest travel time: ${sorted[0].pcode === "KH12" ? "✅ yes" : `❌ no (shortest is ${sorted[0].name_en}; Phnom Penh ${pp.travel_motor_mean_min} min)`}`);
  say(`- Phnom Penh highest facility count: ${maxFac.pcode === "KH12" ? `✅ yes (${pp.facilities.total})` : `❌ no (highest is ${maxFac.name_en} with ${maxFac.facilities.total}; Phnom Penh ${pp.facilities.total})`}`);
  const remote = ["KH11", "KH16", "KH13", "KH19"];
  const rank = (pc: string) => sorted.findIndex((p) => p.pcode === pc) + 1;
  say(`- Remote provinces' rank (1 = shortest, 25 = longest): ${remote.map((pc) => `${provRecs.find((p) => p.pcode === pc)!.name_en} ${rank(pc)}`).join(" · ")}`);
  say();

  say("## 7. Cross-check: MAP (2019, motorised) vs HeiGIT (2026, car, primary health care)");
  say();
  if (hgUnmatched.size) say(`HeiGIT province names not matched: ${[...hgUnmatched].join(", ")}`);
  const pairs = provRecs.filter((p) => hgProv.get(p.pcode) && Number.isFinite(hgProv.get(p.pcode)!.s30) && p.pct_motor_over_30_min !== null);
  const mapWithin30 = pairs.map((p) => 100 - (p.pct_motor_over_30_min as number));
  const hgWithin30 = pairs.map((p) => hgProv.get(p.pcode)!.s30);
  const r = pearson(mapWithin30, hgWithin30);
  say(`Share of people within 30 min of care, per province: MAP (motorised, any facility) vs HeiGIT (car, primary health care). Provinces compared: ${pairs.length}/25. **Pearson r = ${r.toFixed(2)}**.`);
  say();
  say("| Province | MAP ≤ 30 min | HeiGIT ≤ 30 min | HeiGIT ≤ 60 min |");
  say("|---|---:|---:|---:|");
  pairs.forEach((p, i) => say(`| ${p.name_en} | ${mapWithin30[i].toFixed(1)}% | ${hgWithin30[i].toFixed(1)}% | ${hgProv.get(p.pcode)!.s60.toFixed(1)}% |`));
  say();
  say("The two sources use different years, facility lists, road data and travel modes, so levels differ; the cross-check is about whether the same provinces come out as well or poorly served.");
  say();

  // ---------------------------------------------------------------- national context
  const who = parseCsv(read("opendata/who/noncommunicable_diseases_indicators_khm.csv")).filter((x) => !x[0].startsWith("#"));
  const wH = who[0];
  const wI = (n: string) => wH.indexOf(n);
  const latestWho = (code: string, maxYear = 2025) => {
    const rows = who.slice(1).filter((x) => x[0] === code && /BTSX/.test(x[wI("DIMENSION (CODE)")]) && Number(x[wI("YEAR (DISPLAY)")]) <= maxYear);
    rows.sort((a, b) => Number(b[wI("YEAR (DISPLAY)")]) - Number(a[wI("YEAR (DISPLAY)")]));
    const x = rows[0];
    if (!x) { issues.push(`WHO indicator ${code} not found`); return null; }
    return { code, label: x[wI("GHO (DISPLAY)")], value: round(Number(x[wI("Numeric")]), 1), low: round(Number(x[wI("Low")]), 1), high: round(Number(x[wI("High")]), 1), year: Number(x[wI("YEAR (DISPLAY)")]), source: "who-gho" };
  };
  const latestGho = (code: string) => {
    const v = (readJson(`opendata/who/gho_${code}.json`).value as Record<string, string | number>[]).filter((x) => /BTSX/.test(String(x.Dim1)));
    v.sort((a, b) => Number(b.TimeDim) - Number(a.TimeDim));
    const x = v[0];
    return { code, value: round(Number(x.NumericValue), 1), low: round(Number(x.Low), 1), high: round(Number(x.High), 1), year: Number(x.TimeDim), source: "who-gho" };
  };
  const wb = parseCsv(read("opendata/worldbank/health_khm.csv")).filter((x) => !x[0].startsWith("#"));
  const latestWb = (code: string) => {
    const rows = wb.filter((x) => x[4] === code && x[5] !== "").sort((a, b) => Number(b[2]) - Number(a[2]));
    const x = rows[0];
    if (!x) { issues.push(`World Bank indicator ${code} not found`); return null; }
    return { code, label: x[3], value: round(Number(x[5]), 1), year: Number(x[2]), source: "world-bank-health" };
  };
  const national = {
    note: "National estimates for Cambodia (both sexes). WHO values are modelled estimates with uncertainty ranges. Tobacco: latest year ≤ 2025 (WHO also publishes projections to 2030, not used).",
    indicators: {
      diabetes_prevalence_agestd_pct: latestWho("NCD_DIABETES_PREVALENCE_AGESTD"),
      hypertension_30_79_agestd_pct: { ...latestGho("NCD_HYP_PREVALENCE_A"), label: "Hypertension among adults aged 30-79 years, prevalence, age-standardized" },
      hypertension_diagnosed_pct: { ...latestGho("NCD_HYP_DIAGNOSIS_A"), label: "Hypertension: diagnosis coverage among adults aged 30-79 with hypertension, age-standardized" },
      hypertension_controlled_pct: { ...latestGho("NCD_HYP_CONTROL_A"), label: "Hypertension effective treatment coverage (controlled) among adults aged 30-79, age-standardized" },
      overweight_adults_agestd_pct: latestWho("NCD_BMI_25A"),
      obesity_adults_agestd_pct: latestWho("NCD_BMI_30A"),
      insufficient_physical_activity_pct: latestWho("NCD_PAA"),
      tobacco_smoking_agestd_pct: latestWho("M_Est_smk_curr_std"),
      ncd_premature_mortality_30_70_pct: latestWho("NCDMORT3070"),
      health_expenditure_per_capita_usd: latestWb("SH.XPD.CHEX.PC.CD"),
      out_of_pocket_share_of_health_spending_pct: latestWb("SH.XPD.OOPC.CH.ZS"),
    },
    dhs_national_2021: Object.fromEntries(
      dhsNat.filter((x) => String(x.CharacteristicLabel) === "Total" || x.IsTotal === 1).map((x) => [DHS_KEYS[String(x.IndicatorId)], round(Number(x.Value), 1)]),
    ),
  };
  write("national_context.json", stableStringify(national, 1));

  // ---------------------------------------------------------------- WFP vegetable/fruit prices
  const wfp = parseCsv(read("opendata/wfp/wfp_food_prices_khm.csv"));
  const fH = wfp[0];
  const fI = (n: string) => fH.indexOf(n);
  const rows = wfp.slice(1).filter((x) => !x[0].startsWith("#") && x[fI("category")] === "vegetables and fruits" && x[fI("pricetype")] === "Retail" && x[fI("currency")] === "KHR" && x[fI("unit")] === "KG");
  const maxDate = rows.map((x) => x[fI("date")]).sort().at(-1)!;
  const from = `${Number(maxDate.slice(0, 4)) - 1}${maxDate.slice(4)}`;
  const recent = rows.filter((x) => x[fI("date")] > from);
  const prices = new Map<string, Map<string, number[]>>();
  const wfpUnmatched = new Set<string>();
  for (const x of recent) {
    const pc = matchProvince(x[fI("admin1")]);
    if (!pc) { wfpUnmatched.add(x[fI("admin1")]); continue; }
    if (!prices.has(pc)) prices.set(pc, new Map());
    const m = prices.get(pc)!;
    const c = x[fI("commodity")];
    if (!m.has(c)) m.set(c, []);
    m.get(c)!.push(Number(x[fI("price")]));
  }
  const food = {
    note: `Median retail price (KHR per kg) of vegetables and fruit at WFP-monitored markets, ${from} to ${maxDate}. Provinces without WFP markets are absent.`,
    period: { from, to: maxDate },
    source: "wfp-food-prices",
    provinces: Object.fromEntries(
      [...prices].sort((a, b) => a[0].localeCompare(b[0])).map(([pc, m]) => [
        pc,
        Object.fromEntries([...m].sort((a, b) => a[0].localeCompare(b[0])).map(([c, v]) => [c, { median_khr_per_kg: Math.round(median(v)), observations: v.length }])),
      ]),
    ),
  };
  write("food_prices_province.json", stableStringify(food, 1));
  say("## 8. WFP food prices");
  say();
  say(`- Retail vegetable/fruit prices in KHR/kg, ${from} → ${maxDate}: ${recent.length} observations, ${prices.size} provinces. Missing provinces: ${provinces.filter((p) => !prices.has(p.pcode)).map((p) => p.name).join(", ") || "none"}. Unmatched WFP names: ${[...wfpUnmatched].join(", ") || "none"}.`);
  say();

  // ---------------------------------------------------------------- simplified boundaries
  console.log("simplifying boundaries…");
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const mapshaper = require("mapshaper");
  const simplify = async (src: string, out: string, fields: string, pct: string) => {
    await mapshaper.runCommands(
      `-i "${path.join(RAW, "admin", src)}" -filter-fields ${fields} -simplify ${pct} keep-shapes -o "${path.join(CLEAN, out)}" format=geojson precision=0.0001`,
    );
    return fs.statSync(path.join(CLEAN, out)).size;
  };
  const sizes = {
    province: await simplify("khm_admin1.geojson", "boundaries_province.geojson", "adm1_pcode,adm1_name", "10%"),
    district: await simplify("khm_admin2.geojson", "boundaries_district.geojson", "adm2_pcode,adm2_name,adm1_pcode", "12%"),
    commune: await simplify("khm_admin3.geojson", "boundaries_commune.geojson", "adm3_pcode,adm3_name,adm2_pcode,adm1_pcode", "15%"),
  };
  say("## 9. Simplified boundaries for web maps");
  say();
  for (const [k, v] of Object.entries(sizes)) say(`- boundaries_${k}.geojson: ${(v / 1024 / 1024).toFixed(2)} MB ${v < 2 * 1024 * 1024 ? "✅ < 2 MB" : "❌ over 2 MB"}`);
  if (Object.values(sizes).some((v) => v >= 2 * 1024 * 1024)) issues.push("A boundary file is over 2 MB");
  say();

  // ---------------------------------------------------------------- manifest
  const downloads: Record<string, { downloaded: string }> = fs.existsSync(path.join(RAW, "opendata/downloads.json"))
    ? JSON.parse(read("opendata/downloads.json"))
    : {};
  const manifest = {
    note: "Provenance of every open dataset used by SokhaPheap. SHA-256 of each raw input file as used for the current data/clean outputs.",
    datasets: DATASETS.map((d) => ({
      id: d.id, name: d.name, publisher: d.publisher, url: d.url, licence: d.licence, licence_url: d.licenceUrl ?? null,
      data_year: d.dataYear, geographic_level: d.level, used_for: d.usedFor, notes: d.notes ?? null,
      files: d.files.map((f) => {
        const abs = path.join(RAW, f.path);
        return {
          path: `data/raw/${f.path}`,
          source_url: f.url ?? null,
          sha256: sha256(abs),
          bytes: fs.statSync(abs).size,
          downloaded: downloads[f.path]?.downloaded ?? "2026-11-22 (facility pipeline, see data/SOURCES.md)",
        };
      }),
    })),
    derived_inputs: [{ path: "data/clean/facilities.geojson", sha256: sha256(path.join(CLEAN, "facilities.geojson")), built_by: "npm run data:clean" }],
  };
  fs.writeFileSync(path.join(ROOT, "data/manifest.json"), stableStringify(manifest, 1));

  say("## 10. Summary");
  say();
  say(issues.length ? `**Issues needing attention:**\n\n${issues.map((i) => `- ${i}`).join("\n")}` : "No blocking issues found.");
  write("data_quality_report.md", report.join("\n") + "\n");
  console.log(`\nwrote data/clean/*.json, boundaries_*.geojson, data_quality_report.md and data/manifest.json`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
