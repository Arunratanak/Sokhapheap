/**
 * Generates src/lib/scoring/whoCvdTable.ts from the official WHO PDF:
 *   HEARTS technical package — Risk-based CVD management (WHO 2020, ISBN 9789240001367),
 *   Annex 3, page 65: "WHO cardiovascular disease risk non-laboratory-based charts — South-East Asia"
 *   (countries listed on the page include Cambodia).
 *
 * The chart's cell values are real text in the PDF, so they are read by position — no manual
 * transcription. The script fails loudly unless exactly 700 cells are found.
 *
 * Run: npm run data:who-chart
 */
import fs from "node:fs";
import path from "node:path";
import { getDocument } from "pdfjs-dist/legacy/build/pdf.mjs";

const PDF_URL = "https://iris.who.int/server/api/core/bitstreams/aef55845-a638-45d0-b816-70dd5bf8885a/content";
const PDF = path.resolve(__dirname, "../data/raw/who/hearts_risk_based_cvd.pdf");
const OUT = path.resolve(__dirname, "../src/lib/scoring/whoCvdTable.ts");
const PAGE = 65;

const AGES = ["70-74", "65-69", "60-64", "55-59", "50-54", "45-49", "40-44"]; // top → bottom on page
const SBPS = [">=180", "160-179", "140-159", "120-139", "<120"]; // top → bottom within an age block
const BLOCKS = [
  { sex: "male", smoker: false, x: 147.8 },
  { sex: "male", smoker: true, x: 229.6 },
  { sex: "female", smoker: false, x: 311.5 },
  { sex: "female", smoker: true, x: 393.3 },
] as const;
const COL_STEP = 14.55; // BMI columns: <20, 20-24, 25-29, 30-35, >=35
const AGE_TOP_Y = [671.6, 608.2, 544.9, 481.5, 418.2, 354.8, 291.4];
const ROW_STEP = 10.95;

async function main() {
  if (!fs.existsSync(PDF)) {
    fs.mkdirSync(path.dirname(PDF), { recursive: true });
    const res = await fetch(PDF_URL);
    if (!res.ok) throw new Error(`Download the WHO PDF manually from ${PDF_URL} to ${PDF}`);
    fs.writeFileSync(PDF, Buffer.from(await res.arrayBuffer()));
  }
  const doc = await getDocument({ data: new Uint8Array(fs.readFileSync(PDF)) }).promise;
  const page = await doc.getPage(PAGE);
  const all = (await page.getTextContent()).items
    .filter((i): i is typeof i & { str: string; transform: number[] } => "str" in i)
    .map((i) => ({ s: i.str.trim(), x: i.transform[4], y: i.transform[5] }));

  const text = all.map((i) => i.s).join(" ");
  if (!/South-East Asia/.test(text) || !/Cambodia/.test(text) || !/Non-laboratory-based risk chart/.test(text))
    throw new Error(`Page ${PAGE} is not the South-East Asia non-laboratory chart — has the PDF changed?`);

  const nums = all.filter((o) => /^\d+$/.test(o.s) && o.y > 240 && o.y < 680 && o.x > 140 && o.x < 460);
  const used = new Set<object>();
  // table[sex][smoker][age][sbp] = [5 BMI columns]
  const table: Record<string, Record<string, Record<string, Record<string, number[]>>>> = {};
  for (const [ai, age] of AGES.entries())
    for (const [si, sbp] of SBPS.entries()) {
      const y = AGE_TOP_Y[ai] - si * ROW_STEP;
      for (const b of BLOCKS) {
        const row: number[] = [];
        for (let c = 0; c < 5; c++) {
          const x = b.x + c * COL_STEP;
          const hits = nums.filter((o) => Math.abs(o.y - y) < 4 && Math.abs(o.x - x) < 6);
          if (hits.length !== 1) throw new Error(`Cell ${b.sex}/${b.smoker}/${age}/${sbp}/${c}: ${hits.length} matches`);
          used.add(hits[0]);
          row.push(Number(hits[0].s));
        }
        const smk = b.smoker ? "smoker" : "nonSmoker";
        ((((table[b.sex] ??= {})[smk] ??= {})[age] ??= {})[sbp] = row);
      }
    }
  if (used.size !== 700 || nums.length !== 700) throw new Error(`Expected 700 cells, got ${used.size}/${nums.length}`);

  const ts = `// AUTO-GENERATED by scripts/extract_who_cvd_chart.ts — do not edit by hand.
//
// Source: WHO. HEARTS technical package for cardiovascular disease management in primary health care:
// risk-based CVD management. Geneva: World Health Organization; 2020. ISBN 9789240001367.
// Annex 3, PDF page ${PAGE}: "WHO cardiovascular disease risk non-laboratory-based charts — South-East Asia"
// (countries: Cambodia, Indonesia, Lao PDR, Malaysia, Maldives, Mauritius, Myanmar, Philippines,
// Seychelles, Sri Lanka, Thailand, Timor-Leste, Viet Nam). Licence: CC BY-NC-SA 3.0 IGO.
//
// Values are 10-year risk (%) of a fatal or non-fatal cardiovascular event, read from the PDF text layer.
// Extraction checks: exactly 700 cells; monotonic in age, SBP and smoking (see whoCvd.test.ts).
// VERIFIED_BY: TODO(VERIFY) — 10 sample cells listed in REVIEW.md for a human check against page ${PAGE}.

export const WHO_CVD_SOURCE = {
  title: "WHO CVD risk non-laboratory-based chart — South-East Asia (HEARTS, 2020)",
  isbn: "9789240001367",
  page: ${PAGE},
  url: "https://www.who.int/publications/i/item/9789240001367",
} as const;

export const AGE_GROUPS = ${JSON.stringify([...AGES].reverse())} as const;
export const SBP_GROUPS = ${JSON.stringify([...SBPS].reverse())} as const;
export const BMI_GROUPS = ["<20", "20-24", "25-29", "30-35", ">=35"] as const;

export type AgeGroup = (typeof AGE_GROUPS)[number];
export type SbpGroup = (typeof SBP_GROUPS)[number];
type Row = readonly [number, number, number, number, number];

/** WHO_CVD_TABLE[sex][smoker][ageGroup][sbpGroup][bmiColumn] = 10-year risk % */
export const WHO_CVD_TABLE: Record<
  "male" | "female",
  Record<"smoker" | "nonSmoker", Record<AgeGroup, Record<SbpGroup, Row>>>
> = ${JSON.stringify(table, null, 2)};
`;
  fs.writeFileSync(OUT, ts);
  console.log(`Wrote ${OUT} (700 cells from page ${PAGE}).`);
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
